export function translate(lang: LanguageCode, key: string): string {
  return DICTS[lang]?.[key] ?? DICTS.en?.[key] ?? DICTS.id[key] ?? key
}

export function getLanguageMeta(code: LanguageCode): LanguageMeta {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0]
}
